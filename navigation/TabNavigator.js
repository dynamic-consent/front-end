// 탭 아이콘들은 위에서 직접 import한 원본 SVG 파일들을 사용


const Tab = createBottomTabNavigator();

export default function TabNavigator() {
  return (
    <NavigationContainer>
      <Tab.Navigator
        initialRouteName="홈"
        screenOptions={({ route }) => ({
          headerShown: false,

          // ✅ 기본 라벨을 '하나만' 사용
          tabBarShowLabel: true,

          // 라벨 스타일(조금 크게/굵게)
          tabBarLabelStyle: {
            fontSize: 11,
            fontWeight: '600',
            marginTop: 0,
            marginBottom: 2,
          },

          // 라벨 색
          tabBarActiveTintColor: '#00752F',
          tabBarInactiveTintColor: '#7B8E82',

          // 탭바 스타일
          tabBarStyle: {
            backgroundColor: '#F5F7F6',
            borderTopWidth: 0.5,
            borderTopColor: '#E1E9E4',
            height: 60,
            paddingTop: 0,
            paddingBottom: 4,
          },

          // ✅ 아이콘만 렌더 (원본 SVG 파일 내용을 react-native-svg로 구현)
        tabBarIcon: ({ focused, color }) => {
          const size = 28;
          
          if (route.name === '홈') {
            // 홈 탭은 home.svg 사용 (건물 모양 아이콘)
            return focused ? <HomeActiveIcon width={size} height={size} /> : <HomeIcon width={size} height={size} />;
          }
          if (route.name === '기관') {
            // 기관 탭은 org.svg 사용 (사람 모양 아이콘 - org.svg 내용)
            return focused ? <OrgActiveIcon width={size} height={size} /> : <OrgIcon width={size} height={size} />;
          }
          if (route.name === 'MY') {
            // MY 탭은 my.svg 사용 (사람 모양 아이콘)
            return focused ? <MyActiveIcon width={size} height={size} /> : <MyIcon width={size} height={size} />;
          }
          return <View />;
        },
        })}
      >
        {/* ⚠️ 각 스크린 options에 tabBarLabel 함수/텍스트 넣지 말기! */}
        <Tab.Screen name="기관" component={OrgStack} />
        <Tab.Screen name="홈" component={HomeStack} />
        <Tab.Screen name="MY" component={MyScreen} />

      </Tab.Navigator>
    </NavigationContainer>
  );
}
